# Download and load dataset from Kaggle
od.download("https://www.kaggle.com/datasets/pavansubhasht/ibm-hr-analytics-attrition-dataset")
df = pd.read_csv("/content/ibm-hr-analytics-attrition-dataset/WA_Fn-UseC_-HR-Employee-Attrition.csv")

# Preprocessing the data:
# Convert 'Attrition' column to numerical (1 for 'Yes' and 0 for 'No')
df['Attrition'] = df['Attrition'].map({'Yes': 1, 'No': 0})
# Drop irrelevant columns
df = df.drop(columns=['EmployeeNumber', 'Over18', 'EmployeeCount', 'StandardHours'])

# Mapping categorical values to numerical values for encoding
gender_map = {'Male': 1, 'Female': 0}
overtime_map = {'Yes': 1, 'No': 0}
department_map = {v: i for i, v in enumerate(df['Department'].unique())}
jobrole_map = {v: i for i, v in enumerate(df['JobRole'].unique())}
education_map = {'Below College': 1, 'College': 2, 'Bachelor': 3, 'Master': 4, 'Doctor': 5}
env_satisfaction_map = {'Low': 1, 'Medium': 2, 'High': 3, 'Very High': 4}
job_involvement_map = {'Low': 1, 'Medium': 2, 'High': 3, 'Very High': 4}
job_satisfaction_map = {'Low': 1, 'Medium': 2, 'High': 3, 'Very High': 4}
performance_rating_map = {'Low': 1, 'Good': 2, 'Excellent': 3, 'Outstanding': 4}
relationship_satisfaction_map = {'Low': 1, 'Medium': 2, 'High': 3, 'Very High': 4}
worklife_balance_map = {'Bad': 1, 'Good': 2, 'Better': 3, 'Best': 4}

# Label Encoding for categorical columns
label_enc = LabelEncoder()
for col in df.select_dtypes(include=['object']).columns:
    df[col] = label_enc.fit_transform(df[col])

# Separating features (X) and target variable (y)
X = df.drop('Attrition', axis=1)
y = df['Attrition']

# Further encoding for some categorical variables
X['BusinessTravel'] = label_enc.fit_transform(X['BusinessTravel'])
X = pd.get_dummies(X, columns=['EducationField', 'MaritalStatus', 'JobRole'], drop_first=True)

# Scaling the features using StandardScaler
scaler = StandardScaler()
X_scaled = pd.DataFrame(scaler.fit_transform(X), columns=X.columns)

# Splitting the dataset into training and testing sets (80/20 split)
X_train, X_test, y_train, y_test = train_test_split(X_scaled, y, test_size=0.2, random_state=42)

# Model training: Using Random Forest Classifier
model = RandomForestClassifier()
model.fit(X_train, y_train)

# Saving and loading the trained model and scaler using pickle
pickle.dump(model, open('model.pkl', 'wb'))
pickle.dump(scaler, open('scaler.pkl', 'wb'))
model = pickle.load(open('model.pkl', 'rb'))
scaler = pickle.load(open('scaler.pkl', 'rb'))

# Prediction function: Predict employee attrition based on input details
def predict_attrition(name, age, income, jobrole, overtime, edu, gender, years, dept,
                      env_sat, job_inv, job_sat, perf, rel_sat, wlb):
    try:
        input_dict = {
            'Age': age,
            'MonthlyIncome': income,
            'JobRole': jobrole_map[jobrole],
            'OverTime': overtime_map[overtime],
            'Education': education_map[edu],
            'Gender': gender_map[gender],
            'YearsAtCompany': years,
            'Department': department_map[dept],
            'EnvironmentSatisfaction': env_satisfaction_map[env_sat],
            'JobInvolvement': job_involvement_map[job_inv],
            'JobSatisfaction': job_satisfaction_map[job_sat],
            'PerformanceRating': performance_rating_map[perf],
            'RelationshipSatisfaction': relationship_satisfaction_map[rel_sat],
            'WorkLifeBalance': worklife_balance_map[wlb]
        }
        # Convert the input data to a DataFrame and ensure it's aligned with the training data
        input_df = pd.DataFrame([input_dict])
        input_df = input_df.reindex(columns=X.columns, fill_value=0)
        input_scaled = scaler.transform(input_df)  # Scaling the input data
        pred = model.predict(input_scaled)[0]  # Model prediction
        prob = model.predict_proba(input_scaled)[0][1]  # Probability of attrition
        # Classify the risk of attrition based on probability
        if prob < 0.3:
            risk = "Low 🟢"
        elif prob < 0.5:
            risk = "Moderate 🟡"
        else:
            risk = "High 🔴"
        return f"{name} has {risk} chances of leaving the company. ({prob:.2f} probability)"
    except Exception as e:
        return f"Error: {str(e)}"

# Graph plotting functions for different visualizations
def plot_pie_chart():
    fig, ax = plt.subplots()
    df['Attrition'].value_counts().plot.pie(autopct='%1.1f%%', labels=["No", "Yes"], colors=["green", "red"], ax=ax)
    ax.set_ylabel('')
    ax.set_title('Attrition Distribution')
    return fig

def plot_bar_graph():
    fig, ax = plt.subplots()
    df['Department'].value_counts().plot.bar(color='skyblue', ax=ax)
    ax.set_title('Employees per Department')
    return fig

def plot_histogram():
    fig, ax = plt.subplots()
    df['MonthlyIncome'].plot.hist(bins=10, color='orange', edgecolor='black', ax=ax)
    ax.set_title('Monthly Income Distribution')
    return fig

def plot_scatter_plot():
    fig, ax = plt.subplots()
    ax.scatter(df['Age'], df['MonthlyIncome'], color='purple')
    ax.set_xlabel('Age')
    ax.set_ylabel('Monthly Income')
    ax.set_title('Age vs Income Scatter Plot')
    return fig

# Password validation function
def is_valid_password(password):
    if len(password) < 8:  # Password must be at least 8 characters
        return False
    if not re.search(r"[0-9]", password):  # Must contain at least 1 number
        return False
    if not re.search(r"[!@#$%^&*(),.?\":{}|<>]", password):  # Must contain at least 1 special character
        return False
    return True

